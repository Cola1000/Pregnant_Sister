# lookup tables for galois_mult
MUL2 = [0] * 0x100
MUL3 = [0] * 0x100

for i in range(256):
    m2 = (i << 1) ^ 0x1B if (i & 0x80) else (i << 1)
    MUL2[i] = m2 & 0xFF
    MUL3[i] = MUL2[i] ^ i

